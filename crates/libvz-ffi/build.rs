use std::collections::BTreeSet;
use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    println!("cargo:rerun-if-changed=src/");
    println!("cargo:rerun-if-changed=cbindgen.toml");

    let crate_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap_or_else(|_| ".".into()));
    let config_path = crate_dir.join("cbindgen.toml");
    let config = cbindgen::Config::from_file(&config_path)
        .unwrap_or_else(|e| panic!("failed to load cbindgen.toml: {e}"));

    let include_dir = crate_dir.join("include");
    let _ = fs::create_dir_all(&include_dir);

    let out_c = include_dir.join("vz.h");
    cbindgen::Builder::new()
        .with_crate(&crate_dir)
        .with_config(config)
        .generate()
        .expect("unable to generate C bindings via cbindgen")
        .write_to_file(&out_c);

    // Verify all C API functions declared in the freshly generated `vz.h` are covered by
    // the auto-generated C++17 RAII wrapper `vz.hpp` so C and C++ never drift.
    let c_header = fs::read_to_string(&out_c).expect("failed to read generated include/vz.h");
    let exported_fns = collect_vz_functions(&c_header);
    let cpp_header = render_cpp_hpp();
    for sym in &exported_fns {
        assert!(
            cpp_header.contains(sym.as_str()),
            "build.rs codegen parity error: C API function `{sym}` from vz.h is not wrapped in generated vz.hpp"
        );
    }

    let out_cpp = include_dir.join("vz.hpp");
    let prev_cpp = fs::read_to_string(&out_cpp).ok();
    if prev_cpp.as_deref() != Some(cpp_header.as_str()) {
        fs::write(&out_cpp, cpp_header).expect("failed to write generated include/vz.hpp");
    }
}

fn collect_vz_functions(header: &str) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    for line in header.lines() {
        let trimmed = line.trim();
        if let Some(pos) = trimmed.find("vz_") {
            let rest = &trimmed[pos..];
            if let Some(paren) = rest.find('(') {
                let name = rest[..paren].trim();
                if !name.is_empty() && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') {
                    out.insert(name.to_string());
                }
            }
        }
    }
    out
}

